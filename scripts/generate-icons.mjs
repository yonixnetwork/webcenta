// Generates every logo size from the OFFICIAL Webcenta logo
// (public/brand/webcenta-logo-original.png, kept unchanged). Outputs are committed:
//   npm run brand:icons
import sharp from "sharp";
import { mkdirSync, writeFileSync } from "node:fs";

const SRC = "public/brand/webcenta-logo-original.png";
const BLACK = { r: 0, g: 0, b: 0, alpha: 1 };
mkdirSync("public/icons", { recursive: true });
mkdirSync("public/brand", { recursive: true });

/** The logo at `size`, with rounded transparent corners (app-tile look). */
async function rounded(size) {
  const r = Math.round(size * 0.22);
  const mask = Buffer.from(`<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}"><rect width="${size}" height="${size}" rx="${r}" ry="${r}"/></svg>`);
  return sharp(SRC).resize(size, size).composite([{ input: mask, blend: "dest-in" }]).png({ compressionLevel: 9 });
}
/** Full-bleed square (iOS and Android apply their own mask); `scale` < 1 keeps the mark in the safe zone. */
async function square(size, scale = 1) {
  const inner = Math.round(size * scale);
  const pad = Math.floor((size - inner) / 2);
  return sharp(SRC).resize(inner, inner).extend({ top: pad, left: pad, right: size - inner - pad, bottom: size - inner - pad, background: BLACK }).flatten({ background: BLACK }).png({ compressionLevel: 9 });
}

for (const s of [192, 512]) {
  await (await rounded(s)).toFile(`public/icons/icon-${s}.png`);
  // Maskable icons: the swoosh must stay inside the 80% safe circle.
  await (await square(s, 0.8)).toFile(`public/icons/maskable-${s}.png`);
}
await (await square(180)).toFile("public/icons/apple-touch-icon.png");
for (const s of [16, 32, 48]) await (await rounded(s)).toFile(`public/icons/favicon-${s}.png`);
for (const s of [64, 128]) await (await rounded(s)).toFile(`public/brand/logo-mark-${s}.png`);

// Default social preview (Open Graph / Twitter), 1200×630.
const mark = await (await rounded(440)).toBuffer();
await sharp({ create: { width: 1200, height: 630, channels: 4, background: BLACK } })
  .composite([{ input: mark, left: 380, top: 95 }]).png({ compressionLevel: 9 }).toFile("public/brand/og-default.png");

// A small copy for the self-contained static error pages (their CSP allows data: images only).
const tiny = await (await rounded(64)).toBuffer();
writeFileSync("src/lib/brand-mark-data.ts", `// Generated by scripts/generate-icons.mjs from the official logo. Do not edit.\nexport const BRAND_MARK_DATA_URI = "data:image/png;base64,${tiny.toString("base64")}";\n`);
console.log("brand assets written");
